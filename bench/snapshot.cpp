std::vector<Search> split_searches(std::string_view all) {
    std::vector<Search> searches;
    auto start = all.starts_with("## ") ? 0 : all.find("\n## ");
    if (start == std::string_view::npos) {
        return searches;
    }
    std::string_view rest = all.substr(all.starts_with("## ") ? 0 : start + 1);
    while (rest.starts_with("## ")) {
        const auto eol = rest.find('\n');
        if (eol == std::string_view::npos) {
            break;
        }
        std::string formula{rest.substr(3, eol - 3)};
        rest = rest.substr(eol + 1);
        const auto next = rest.find("\n## ");
        const auto end = next == std::string_view::npos ? rest.size() : next + 1;
        searches.emplace_back(std::move(formula), rest.substr(0, end));
        rest = rest.substr(end);
    }
    return searches;
}

