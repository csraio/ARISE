core::Result<std::vector<SearchResults>> results(const std::vector<Search>& searches,
                                                 const BenchmarkCase& benchmark_case) {
    constexpr std::array kScenarios{Scenario::Worst, Scenario::Typical, Scenario::NoDept};
    std::array<Evidence, kScenarios.size()> evidence;
    for (std::size_t s = 0; s < kScenarios.size(); ++s) {
        auto e = evidence_for(kScenarios[s], benchmark_case);
        if (!e) {
            return e.error();
        }
        evidence[s] = std::move(e).value();
    }
    std::vector<SearchResults> all;
    for (const auto& [formula, csv] : searches) {
        const auto imported = clean(csv);
        if (!imported) {
            return imported.error();
        }
        const auto parsed = parse(imported.value());
        std::array<std::vector<filter::CarbonFit>, kScenarios.size()> fits;
        const bool with_fits = formula == benchmark_case.formula;
        for (std::size_t s = 0; with_fits && s < kScenarios.size(); ++s) {
            auto pruned = prune(parsed.molecules, evidence[s]);
            if (!pruned) {
                return pruned.error();
            }
            fits[s] = std::move(pruned).value();
        }
        SearchResults search{.formula = formula, .lines = {}};
        for (std::size_t i = 0; i < parsed.molecules.size(); ++i) {
            const auto equivalence = chem::nmr_equivalence(parsed.molecules[i]);
            std::string line =
                parsed.smiles[i] + "\t" + join(equivalence.fewest) + "\t" + join(equivalence.most);
            for (std::size_t s = 0; with_fits && s < kScenarios.size(); ++s) {
                line += "\t" + describe(fits[s][i]);
            }
            search.lines.push_back(std::move(line));
        }
        all.push_back(std::move(search));
    }
    return all;
}

std::string fingerprint(std::string_view text) {
    constexpr std::uint64_t kOffset = 14695981039346656037ULL;
    constexpr std::uint64_t kPrime = 1099511628211ULL;
    std::uint64_t hash = kOffset;
    for (const char c : text) {
        hash ^= static_cast<std::uint8_t>(c);
        hash *= kPrime;
    }
    constexpr std::string_view kDigits = "0123456789abcdef";
    std::string hex(16, '0');
    for (std::size_t i = 0; i < hex.size(); ++i) {
        hex[hex.size() - 1 - i] = kDigits[(hash >> (4 * i)) & 0xFU];
    }
    return hex;
}

std::string snapshot(const std::vector<SearchResults>& all) {
    std::string text;
    for (const auto& search : all) {
        text += "## " + search.formula + " " + std::to_string(search.lines.size()) + "\n";
        for (const auto& line : search.lines) {
            text += fingerprint(line) + "\n";
        }
    }
    return text;
}

