std::string join(const std::vector<std::size_t>& values) {
    std::string text;
    for (const auto value : values) {
        text += (text.empty() ? "" : " ") + std::to_string(value);
    }
    return text;
}

std::string describe(const filter::CarbonFit& fit) {
    std::string text{filter::to_string(fit.verdict.tier)};
    text += " " + std::to_string(fit.assumed_overlaps);
    for (const auto& reason : fit.verdict.reasons) {
        text += " | " + reason;
    }
    return text;
}

